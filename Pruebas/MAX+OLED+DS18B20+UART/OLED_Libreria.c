void OLED_Char(unsigned char c){
    unsigned char i;
    if(c < 32 || c > 126) c = 32; /* Limite ajustado a ASCII 126 */
    for(i = 0; i < 5; i++){
        OLED_Dato(font5x8[c - 32][i]);
    }
    OLED_Dato(0x00); 
}

void OLED_String(unsigned char pagina, unsigned char col, const char *texto){
    OLED_SetCursor(pagina, col);
    while(*texto != '\0'){
        OLED_Char(*texto);
        texto++;
    }
}


// SE USA EN BME280
unsigned char I2C_Read(unsigned char ack) {
    unsigned char temp;
    I2C_Ready();
    SSPCON2bits.RCEN = 1; 
    while(!SSPSTATbits.BF);
    temp = SSPBUF;
    I2C_Ready();
    SSPCON2bits.ACKDT = (ack) ? 0 : 1; 
    SSPCON2bits.ACKEN = 1;
    return temp;
}

void I2C_Restart(void) {
    I2C_Ready();
    SSPCON2bits.RSEN = 1;
    while(SSPCON2bits.RSEN);
}